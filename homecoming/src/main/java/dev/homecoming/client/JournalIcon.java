package dev.homecoming.client;

import net.minecraft.client.gui.GuiGraphics;

/** One consistent 10x10 pixel family, rendered without fonts or external texture dependencies. */
enum JournalIcon {
    BOOK("0111101110","0100101010","0100101010","0100101010","0100101010","0100101010","0111101110","0000010000","0000010000","0000000000"),
    COMPASS("0001100000","0011110000","0100001000","1001100100","1011100100","1011000100","1000000100","0100001000","0011110000","0000000000"),
    GEAR("0001100000","0101101000","0011110000","0110011000","1110011100","1110011100","0110011000","0011110000","0101101000","0001100000"),
    PIN("0001100000","0010010000","0100001000","0101101000","0101101000","0100001000","0010010000","0001100000","0001100000","0001100000"),
    BELL("0001100000","0011110000","0010010000","0100001000","0100001000","0100001000","1111111100","0000000000","0001100000","0000000000"),
    CHECK("0000000000","0000000010","0000000110","0000001100","0100011000","0110110000","0011100000","0001000000","0000000000","0000000000"),
    ARROW("0000000000","0000100000","0000110000","1111111000","1111111100","1111111000","0000110000","0000100000","0000000000","0000000000"),
    CLOSE("0000000000","0100001000","0010010000","0001100000","0001100000","0010010000","0100001000","0000000000","0000000000","0000000000"),
    LOCK("0001110000","0010001000","0010001000","0010001000","0111111100","0100000100","0101100100","0101100100","0111111100","0000000000"),
    COPY("0011111100","0010000100","1111110100","1000010100","1000011100","1000010000","1000010000","1111110000","0000000000","0000000000"),
    WARNING("0000100000","0001110000","0001110000","0011011000","0011011000","0111011100","0111111100","1111011110","1111111110","0000000000"),
    REFRESH("0001111000","0010000100","0100000010","0100001110","0000001110","1110000000","1110000100","1000000100","0100001000","0011110000"),
    LEAVE("1111100000","1000100000","1000100100","1000100110","1000111111","1000100110","1000100100","1000100000","1111100000","0000000000");
    private final String[] pixels;
    JournalIcon(String... pixels) { this.pixels=pixels; }
    void draw(GuiGraphics graphics,int x,int y,int color) {
        for(int row=0;row<pixels.length;row++)
            for(int col=0;col<pixels[row].length();col++)
                if(pixels[row].charAt(col)=='1') graphics.fill(x+col,y+row,x+col+1,y+row+1,color);
    }
}
